@receiver(post_save, sender=PaypalTransaction)
def update_youpay_transaction_status(sender, instance, **kwargs):
    try:
        logger.info(
            "PaypalTransaction post_save Triggering for "
            "reference {}, status {}".format(
                instance.payment_reference, instance.status))

        payment_reference = instance.payment_reference
        youpay_obj = YouPayTransactionCRUD()
        transaction_obj = (
            youpay_obj.get_youpay_transaction_data_with_payment_reference(
                payment_reference))

        data_to_update = prepare_youpay_transaction_update_data(instance,
                                                                transaction_obj)
        if data_to_update:
            is_youpay_updated = youpay_obj.update_youpay_transaction_data(
                data_to_update)
            if is_youpay_updated:
                logger.info(
                    "PaypalTransaction post_save success for "
                    "reference {}, status {}".format(
                        instance.payment_reference, instance.status))

    except Exception as e:
        logger.error(
            f"Failed to update YouPayTransaction for PayPal payment_reference {instance.payment_reference}: {e}")


def prepare_youpay_transaction_update_data(instance, transaction_obj):
    try:
        if instance.status == PAYPAL_CAPTURE_STATUS_COMPLETED:
            payment_status = PAYMENT_STATUS_PAID
        elif instance.status == PAYPAL_REFUND_STATUS_COMPLETED:
            payment_status = PAYMENT_STATUS_REFUNDED
        else:
            payment_status = transaction_obj.payment_status

        data_to_update = {
            'transaction_id': transaction_obj.transaction_id,
            "payment_status": payment_status,
        }
        return data_to_update
    except Exception as e:
        logger.error("Error while preparing data for youpay transaction "
                     "update for paypal {}".format(e), exc_info=True)
        return None

